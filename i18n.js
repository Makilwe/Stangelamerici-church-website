(function () {
  var STORAGE_KEY = "sam-lang";

  function initialLanguage() {
    try {
      var saved = localStorage.getItem(STORAGE_KEY);
      if (saved && I18N[saved]) return saved;
    } catch (e) { /* storage unavailable */ }
    var nav = (navigator.language || navigator.userLanguage || "en").toLowerCase();
    if (nav.indexOf("es") === 0) return "es";
    if (nav.indexOf("fr") === 0) return "fr";
    if (nav.indexOf("it") === 0) return "it";
    if (nav.indexOf("pt") === 0) return "pt";
    return "en";
  }

  function setText(el, value) {
    if (value.indexOf("<") !== -1) {
      el.innerHTML = value;
    } else {
      el.textContent = value;
    }
  }

  function applyLanguage(lang) {
    var dict = I18N[lang] || I18N.en;
    document.documentElement.setAttribute("lang", lang);

    var nodes = document.querySelectorAll("[data-i18n]");
    for (var i = 0; i < nodes.length; i++) {
      var key = nodes[i].getAttribute("data-i18n");
      if (typeof dict[key] === "string") setText(nodes[i], dict[key]);
    }

    var alts = document.querySelectorAll("[data-i18n-alt]");
    for (var j = 0; j < alts.length; j++) {
      var akey = alts[j].getAttribute("data-i18n-alt");
      if (typeof dict[akey] === "string") alts[j].setAttribute("alt", dict[akey]);
    }

    var arias = document.querySelectorAll("[data-i18n-aria]");
    for (var k = 0; k < arias.length; k++) {
      var rkey = arias[k].getAttribute("data-i18n-aria");
      if (typeof dict[rkey] === "string") arias[k].setAttribute("aria-label", dict[rkey]);
    }

    if (dict["meta.title"]) document.title = dict["meta.title"];
    var md = document.querySelector('meta[name="description"]');
    if (md && dict["meta.desc"]) md.setAttribute("content", dict["meta.desc"]);
    var og = document.querySelector('meta[property="og:description"]');
    if (og && dict["meta.ogdesc"]) og.setAttribute("content", dict["meta.ogdesc"]);

    var btns = document.querySelectorAll(".lang-btn");
    for (var b = 0; b < btns.length; b++) {
      var active = btns[b].getAttribute("data-lang") === lang;
      btns[b].classList.toggle("active", active);
      if (active) {
        btns[b].setAttribute("aria-pressed", "true");
      } else {
        btns[b].removeAttribute("aria-pressed");
      }
    }

    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (e) { /* storage unavailable */ }
  }

  document.addEventListener("DOMContentLoaded", function () {
    applyLanguage(initialLanguage());
    var btns = document.querySelectorAll(".lang-btn");
    for (var i = 0; i < btns.length; i++) {
      btns[i].addEventListener("click", function () {
        applyLanguage(this.getAttribute("data-lang"));
      });
    }
  });
})();
